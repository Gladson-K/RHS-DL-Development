#!/usr/bin/env python3
"""Populate LaTeX macros and result tables for the IEEE paper from JSON.

Writes into ``paper/generated``:
    numbers.tex          - \\newcommand macros for inline numbers
    table_setups.tex     - 5-setup + full-data test metrics tabular body
    table_nas.tex        - NAS search runs comparison tabular body
    table_gp.tex         - GP-vs-model summary tabular body

Missing inputs become ``--`` so the manuscript still compiles mid-study.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / "paper" / "generated"
GEN.mkdir(parents=True, exist_ok=True)

SETUPS = ["mlp", "gnn", "transformer", "hybrid", "hybrid_jev"]


def _load(path):
    p = ROOT / path
    return json.loads(p.read_text()) if p.exists() else None


def _f(v, nd=3):
    try:
        return f"{float(v):.{nd}f}"
    except (TypeError, ValueError):
        return "--"


def _i(v):
    try:
        return f"{int(v):,}"
    except (TypeError, ValueError):
        return "--"


def main():
    setups = _load("search_results/mimo64_setups_full/results.json")
    by = {r["setup"]: r for r in setups["results"]} if setups else {}
    full = _load("search_results/mimo64_full_data/results.json")

    # ---- NAS runs -------------------------------------------------------- #
    nas_runs = {}
    base = ROOT / "search_results/nas_study"
    for d in sorted(base.glob("*")):
        bj = d / "metrics/best.json"
        if bj.exists():
            nas_runs[d.name] = json.loads(bj.read_text())

    # ---- NAS full-data retrain ------------------------------------------ #
    nas_full = None
    for rj in sorted((ROOT / "search_results/nas_full_data").glob("*/results.json")):
        nas_full = json.loads(rj.read_text())
        break

    # ---- macros ---------------------------------------------------------- #
    macro = []
    if full:
        macro += [
            ("HjTestRateR", _f(full["test_rate_r2"])),
            ("HjTestRateMAE", _f(full["test_rate_mae"])),
            ("HjTestMCos", _f(full["test_M_cos"])),
            ("HjTestMnMSE", _f(full["test_M_n_mse"])),
            ("HjTestMR", _f(full["test_M_r2"])),
            ("HjValRateR", _f(full["val_rate_r2"])),
            ("HjValMCos", _f(full["val_M_cos"])),
            ("HjParams", _i(full["parameters"])),
            ("HjLatency", _f(full["latency_ms"], 2)),
            ("HjBestEpoch", _i(full["epochs_reported"])),
            ("HjEpochsRun", _i(full["epochs_run"])),
        ]
    if nas_full:
        macro += [
            ("NasTestRateR", _f(nas_full["test_rate_r2"])),
            ("NasTestRateMAE", _f(nas_full["test_rate_mae"])),
            ("NasTestMCos", _f(nas_full["test_M_cos"])),
            ("NasTestMnMSE", _f(nas_full["test_M_n_mse"])),
            ("NasTestMR", _f(nas_full["test_M_r2"])),
            ("NasParams", _i(nas_full["parameters"])),
            ("NasLatency", _f(nas_full["latency_ms"], 2)),
            ("NasArchName", nas_full["arch_name"].replace("_", r"\_")),
        ]
    lines = ["% auto-generated by scripts/fill_paper_numbers.py"]
    for k, v in macro:
        lines.append(f"\\newcommand{{\\{k}}}{{{v}}}")
    (GEN / "numbers.tex").write_text("\n".join(lines) + "\n")

    # ---- setups table ---------------------------------------------------- #
    rows = []
    for s in SETUPS:
        r = by.get(s)
        if not r:
            continue
        rows.append(
            f"{s} & {_f(r['parameters']/1e6,2)} & {_f(r['latency_ms'],2)} & "
            f"{_f(r['test_rate_r2'])} & {_f(r['test_rate_mae'],2)} & "
            f"{_f(r['test_M_cos'])} & {_f(r['test_M_n_mse'])} & {_f(r['test_M_r2'])} \\\\"
        )
    if full:
        rows.append(
            "\\textbf{hybrid\\_jev (15K)} & "
            f"{_f(full['parameters']/1e6,2)} & {_f(full['latency_ms'],2)} & "
            f"\\textbf{{{_f(full['test_rate_r2'])}}} & {_f(full['test_rate_mae'],2)} & "
            f"\\textbf{{{_f(full['test_M_cos'])}}} & \\textbf{{{_f(full['test_M_n_mse'])}}} & "
            f"\\textbf{{{_f(full['test_M_r2'])}}} \\\\"
        )
    if nas_full:
        rows.append(
            "\\textbf{NAS best (15K)} & "
            f"{_f(nas_full['parameters']/1e6,2)} & {_f(nas_full['latency_ms'],2)} & "
            f"{_f(nas_full['test_rate_r2'])} & {_f(nas_full['test_rate_mae'],2)} & "
            f"{_f(nas_full['test_M_cos'])} & {_f(nas_full['test_M_n_mse'])} & "
            f"{_f(nas_full['test_M_r2'])} \\\\"
        )
    (GEN / "table_setups.tex").write_text("\n".join(rows) + "\n")

    # ---- NAS runs table -------------------------------------------------- #
    rows = []
    for name, doc in nas_runs.items():
        m = doc["metrics"]
        arch = doc.get("architecture", {}).get("hidden_layers", [])
        arch_s = "-".join(str(a) for a in arch)
        rows.append(
            f"{name} & {arch_s} & {_f(m['score'])} & {_f(m['rate_r2'])} & "
            f"{_f(m['beamforming_similarity'])} & {_f(m['parameters']/1e6,2)} & "
            f"{_f(m['latency_ms'],2)} \\\\"
        )
    (GEN / "table_nas.tex").write_text("\n".join(rows) + "\n")

    # ---- GP comparison table -------------------------------------------- #
    rows = []
    if full:
        rows.append(
            f"hybrid\\_jev (15K) & {_f(full['test_rate_mae'],2)} & {_f(full['test_rate_r2'])} & "
            f"{_f(full['test_M_cos'])} & {_f(full['test_M_n_mse'])} \\\\"
        )
    if nas_full:
        rows.append(
            f"NAS best (15K) & {_f(nas_full['test_rate_mae'],2)} & {_f(nas_full['test_rate_r2'])} & "
            f"{_f(nas_full['test_M_cos'])} & {_f(nas_full['test_M_n_mse'])} \\\\"
        )
    for s in SETUPS:
        r = by.get(s)
        if r:
            rows.append(
                f"{s} & {_f(r['test_rate_mae'],2)} & {_f(r['test_rate_r2'])} & "
                f"{_f(r['test_M_cos'])} & {_f(r['test_M_n_mse'])} \\\\"
            )
    (GEN / "table_gp.tex").write_text("\n".join(rows) + "\n")

    print(f"wrote generated LaTeX to {GEN}  (setups={len(by)}, nas_runs={len(nas_runs)}, "
          f"nas_full={bool(nas_full)})")


if __name__ == "__main__":
    main()
